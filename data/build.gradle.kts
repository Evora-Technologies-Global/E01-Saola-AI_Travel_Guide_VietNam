// The API keys live in local.properties (git-ignored) so they never reach version control.
// Read through the provider API so they stay compatible with the configuration cache.
fun localProperty(name: String): Provider<String> = providers
    .fileContents(rootProject.layout.projectDirectory.file("local.properties"))
    .asText
    .map { text ->
        text.lineSequence()
            .map(String::trim)
            .firstOrNull { it.startsWith("$name=") }
            ?.substringAfter('=')
            ?.trim()
            .orEmpty()
    }
    .orElse("")

val geminiApiKey: Provider<String> = localProperty("GEMINI_API_KEY")


/*
 * `BuildConfig` is an Android-only construct, and the data layer is no longer
 * Android-only. The one value the code actually reads from it is generated into
 * commonMain instead, so the same source compiles for the JVM and for Kotlin/Native.
 *
 * Note what is *not* here any more: a `DEBUG` constant. This module is built by
 * `com.android.kotlin.multiplatform.library`, which produces a single Android variant
 * — `:app`'s debug and release builds link the very same class file, so a constant
 * generated here cannot tell them apart. It used to be keyed off `-Psaola.debug`,
 * default `true`, which meant a plain `:app:assembleRelease` shipped with Ktor's
 * `Logging` plugin installed. The flag is now passed in at Koin startup by whoever
 * knows the answer: `BuildConfig.DEBUG` on Android, Swift's `#if DEBUG` on iOS.
 * See `networkModule(isDebug)`.
 */
val generateBuildConfig by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated/buildConfig/commonMain/kotlin")
    val apiKey = geminiApiKey

    outputs.dir(outputDir)
    inputs.property("apiKey", apiKey)

    doLast {
        val dir = outputDir.get().asFile
            .resolve("com/evora/technologies/saola/data")
            .apply { mkdirs() }
        dir.resolve("DataBuildConfig.kt").writeText(
            """
            package com.evora.technologies.saola.data

            /**
             * Generated by the `generateBuildConfig` Gradle task — do not edit.
             *
             * Replaces the Android `BuildConfig` the module used before it became
             * multiplatform. Only the one field the code genuinely consumes is
             * emitted, and it is the same for every build type: the key comes from
             * `local.properties`, not from debug-vs-release.
             */
            internal object DataBuildConfig {
                const val GEMINI_API_KEY: String = "${apiKey.get()}"
            }

            """.trimIndent(),
        )
    }
}

