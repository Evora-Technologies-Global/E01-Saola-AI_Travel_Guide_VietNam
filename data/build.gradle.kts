/**
 * `provinces.json` has to reach the iOS app bundle too.
 *
 * `src/androidMain/assets` is its canonical home — that is the one location Android packages
 * without any extra wiring — and this task copies it next to the Xcode project, which
 * references the folder rather than individual files. Keeping one copy in version control
 * means the 34 outlines can never drift between platforms.
 *
 * `:shared` is what depends on this, because `:shared` owns the framework Xcode links and its
 * link tasks are the only thing Xcode's build phase invokes.
 *
 * `SharedAssets`, not `Resources`: a directory literally named `Resources` at the root of
 * an iOS `.app` makes CFBundle fall back to the legacy bundle layout and look for
 * `Resources/Info.plist`, so the installer cannot read the bundle identifier at all — the app
 * builds fine and then fails to install with "Missing bundle ID".
 */
val copySharedAssetsToIos by tasks.registering(Sync::class) {
    from(layout.projectDirectory.dir("src/androidMain/assets"))
    into(rootProject.layout.projectDirectory.dir("iosApp/SharedAssets"))
}
