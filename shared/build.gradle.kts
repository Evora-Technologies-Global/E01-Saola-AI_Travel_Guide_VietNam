import org.jetbrains.compose.resources.ResourcesExtension

/**
 * Fallback for `vietlens.versionName`, which the root `gradle.properties` declares and `:app`
 * reads for the APK's own version. Only reached if that line is deleted; the point of the
 * property is that the footer on the Settings screen and the APK cannot say different things.
 */
val DEFAULT_VERSION_NAME = "1.0.0"

/**
 * The package the generated `Res` class lives in.
 *
 * Named once because it appears twice: in the `compose.resources` block below, and as a directory
 * inside the iOS bundle layout the resource reader expects.
 */
val RES_PACKAGE = "com.duylt.trave.vietlensai.resources"

plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.android.kotlin.multiplatform.library)
    alias(libs.plugins.compose.multiplatform)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.kotlin.serialization)
}

/*
 * :shared holds the whole presentation layer — every screen, every ViewModel, the
 * navigation graph and the design system — written once against Compose Multiplatform.
 *
 * `:app` is a thin Android host that sets a theme and calls into here, and `iosApp` is
 * an Xcode project that links the framework this module produces. Anything that genuinely
 * differs per platform (the camera, the narration engine, the permission prompts) is an
 * `expect` declaration with an actual in androidMain and iosMain.
 */
/*
 * `BuildConfig` is Android-only, and the Settings screen is not any more. The one field it
 * read — the version name shown in the footer — is generated into commonMain instead.
 */
val generateSharedBuildConfig by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated/buildConfig/commonMain/kotlin")
    val versionName = providers.gradleProperty("vietlens.versionName").orElse(DEFAULT_VERSION_NAME)

    outputs.dir(outputDir)
    inputs.property("versionName", versionName)

    doLast {
        val dir = outputDir.get().asFile
            .resolve("com/duylt/trave/vietlensai")
            .apply { mkdirs() }
        dir.resolve("SharedBuildConfig.kt").writeText(
            """
            package com.duylt.trave.vietlensai

            /** Generated by the `generateSharedBuildConfig` Gradle task — do not edit. */
            internal object SharedBuildConfig {
                const val VERSION_NAME: String = "${versionName.get()}"
            }

            """.trimIndent(),
        )
    }
}

