/*
 * Compose compiler reports, which is what makes recomposition a *testable* property
 * rather than something you notice as jank on a demo phone.
 *
 * For every compilation the plugin writes two files: `…-composables.txt`, which says of
 * each composable whether it is `skippable` and `restartable`, and `…-classes.txt`, which
 * says of each class whether Compose considers it `stable`. A composable that is not
 * skippable re-executes on every recomposition of its parent even when none of its
 * arguments changed; the usual cause is one unstable parameter, and the usual cause of
 * *that* is a class the compiler could not prove immutable.
 *
 * Turned on for every build rather than behind a flag: the reports are a few hundred
 * kilobytes of text and the `composeStabilityCheck` task below reads them, so a build
 * that skipped them would be a build that cannot be verified.
 */
composeCompiler {
    reportsDestination.set(layout.buildDirectory.dir("compose-reports"))
    metricsDestination.set(layout.buildDirectory.dir("compose-reports"))

    // See compose-stability.conf for why the domain layer has to be declared rather
    // than inferred: it is compiled without the Compose plugin, so nothing in it can
    // be proven stable from its bytecode.
    stabilityConfigurationFiles.add(
        layout.projectDirectory.file("compose-stability.conf"),
    )
}

/*
 * `ComposeStabilityReportTest` asserts against the reports the block above produces, so the
 * unit-test task has to know where they are and has to have made sure they exist.
 *
 * The reports are a side effect of compiling rather than a declared task output — the
 * compiler plugin writes them, Gradle does not model them — so they cannot be wired as a
 * task input. The explicit `dependsOn` is what guarantees a report is on disk by the time
 * the test opens it; without it, `test` alone on a clean tree finds nothing and the gate
 * fails for the wrong reason.
 */
tasks.withType<Test>().configureEach {
    dependsOn("compileAndroidMain")
    systemProperty(
        "vietlens.composeReportsDir",
        layout.buildDirectory.dir("compose-reports").get().asFile.absolutePath,
    )
    // `DesignTokenTest` reads the shared sources as text rather than as compiled classes:
    // a hardcoded radius and a `Spacing.lg` compile to the same bytecode, so the only
    // place the difference still exists is the file.
    systemProperty(
        "vietlens.commonMainDir",
        layout.projectDirectory.dir("src/commonMain/kotlin").asFile.absolutePath,
    )
}

/*
 * Compose resources need no wiring of their own.
 *
 * `embedAndSignAppleFrameworkForXcode` — the task Xcode's build phase invokes — pulls in Compose
 * Multiplatform's own `syncComposeResourcesForIos`, which writes straight into
 * `VietLensAI.app/compose-resources`. A hand-rolled copy used to live here, from when the build
 * phase called the raw `link…` task and nothing synced the resources; it is redundant now, and
 * two tasks writing the same tree is how they drift.
 *
 * `provinces.json` is the exception and still needs `:data:copySharedAssetsToIos`: it is a plain
 * asset in `:data`, not a Compose resource, so nothing in the Compose plugin knows about it.
 *
 * One requirement this places on the Xcode project: `ARCHS` must be `arm64` and nothing else.
 * `syncComposeResourcesForIos` maps Xcode's ARCHS to Kotlin targets itself, and for the
 * `iphonesimulator` SDK it recognises only `arm64`/`arm64e` — any other value is
 * `error("Unknown iOS simulator arch: '$arch'")`. Adding an `iosX64()` target would not help,
 * because the plugin has no x86_64 branch to reach it by. So `iosApp.xcodeproj` pins
 * `ARCHS = arm64` in both target configurations, the same as JetBrains' own project template;
 * without it a build for a generic simulator destination gets `arm64 x86_64` and fails here
 * before compiling anything.
 */
tasks.matching { it.name.startsWith("link") && it.name.contains("Ios") }
    .configureEach { dependsOn(":data:copySharedAssetsToIos") }

// The same for the Xcode entry point, which does not go through a `link…` task by that name.
tasks.matching { it.name == "embedAndSignAppleFrameworkForXcode" }
    .configureEach { dependsOn(":data:copySharedAssetsToIos") }
